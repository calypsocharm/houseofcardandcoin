/* Signed-in signal for the static pages.
   index.html and friends are generated by build.js with a fixed header, so they
   cannot tell whether you are signed in — they always drew "Guild Login". This
   asks the server and corrects the header, matching what the EJS pages render.
   The EJS pages already do it server-side and skip this entirely. */
(function () {
  var nav = document.querySelector('.nav-links');
  if (!nav || nav.querySelector('.signal')) return; // EJS page already handled it

  fetch('/api/me', { credentials: 'same-origin' })
    .then(function (r) { return r.ok ? r.json() : null; })
    .then(function (me) {
      if (!me) return;

      var signal = document.createElement('span');
      signal.className = 'signal signal--' + (me.signedIn ? 'in' : 'out');
      signal.textContent = me.signedIn
        ? '● ' + (me.kind === 'patron' ? 'Seated' : 'Signed in') + ' — ' + me.name
        : '● Signed out';

      var loginLink = nav.querySelector('a.nav-login');

      if (!me.signedIn) {
        nav.insertBefore(signal, loginLink || null);
        return;
      }

      // Signed in: swap the login link for the hall and a sign-out control.
      // unread notices, so news reaches you on the static pages too
      if (me.unread) {
        var bell = document.createElement('a');
        bell.className = 'newsbell';
        bell.href = '/board/notices';
        bell.textContent = '✦ ' + me.unread + ' new';
        bell.title = me.unread + ' unread notice' + (me.unread === 1 ? '' : 's');
        nav.insertBefore(bell, loginLink || null);
      }

      var hall = document.createElement('a');
      hall.href = me.kind === 'patron' ? '/board' : '/members';
      hall.textContent = me.kind === 'patron' ? 'Tavern' : 'Guild Hall';

      var form = document.createElement('form');
      form.method = 'post';
      form.action = me.kind === 'patron' ? '/tavern/logout' : '/members/logout';
      form.className = 'nav-logout';
      var out = document.createElement('button');
      out.type = 'submit';
      out.className = 'nav-login';
      out.textContent = me.kind === 'patron' ? 'Leave' : 'Sign out';
      form.appendChild(out);

      if (loginLink) {
        nav.insertBefore(signal, loginLink);
        nav.insertBefore(hall, loginLink);
        nav.replaceChild(form, loginLink);
      } else {
        nav.appendChild(signal);
        nav.appendChild(hall);
        nav.appendChild(form);
      }
    })
    .catch(function () { /* offline or blocked — leave the header as built */ });
})();
